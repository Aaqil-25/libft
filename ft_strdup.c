#include "libft.h"

char	*ft_strdup(const char *str)
{
	char	*s;
	int		i;

	i = 0;
	s = (char *)malloc((ft_strlen(str)+1) * sizeof(char));
	if (!s)
		return (NULL);
	while (str[i])
	{
		s[i] = str[i];
		i++;
	}
	s[i] = '\0';
	return (s);
}
